/**
 * NyayaNow Situation Navigator — understanding layer.
 *
 * ARCHITECTURE (product rule): understanding is SEPARATE from legal truth.
 * This module only answers "what situation is this person describing?". It
 * NEVER generates legal rights, advice, sections or sources. Once a situation
 * is identified, the verified knowledge base (situations.ts / sources.ts) is
 * read for the actual guidance.
 *
 * LAYERED / HYBRID FLOW:
 *   1. safety scan (immediate danger → escalation, never ignored)
 *   2. arrest-uncertainty scan (→ Questioned vs Arrested decision tool)
 *   3. the existing local keyword classifier (fast, offline, private)
 *   4. structured context extraction (traffic, vehicle, phone, money, …)
 *   5. HIGH confidence → verified guide, no external call
 *   6. otherwise, IF the user opted in AND an AI proxy is configured:
 *      the LLM is asked ONLY to understand the situation (structured JSON,
 *      schema-validated). Legal guidance is never generated by the model.
 *   7. dynamic everyday-language clarification (max 3 questions, always an
 *      "I'm not sure" option) when routing is still ambiguous
 *   8. honest UNKNOWN fallback — we never guess about legal rights
 *
 * Nothing is faked: without a configured proxy the local engine IS the
 * understanding layer and the UI says so. AI failure always falls back to the
 * local result — the app never breaks.
 */

export type RouteSituationId = SituationId | 'TRAFFIC_UNVERIFIED'

export type Confidence = 'HIGH' | 'MEDIUM' | 'LOW'

export interface NavigatorContext {
  vehicleInvolved?: boolean
  vehicleType?: string
  documentsRequested?: boolean
  questioning?: boolean
  searchInvolved?: boolean
  propertyInvolved?: boolean
  phoneInvolved?: boolean
  moneyRequested?: boolean
  arrestMentioned?: boolean
  harmMentioned?: boolean
  trafficMentioned?: boolean
  challanMentioned?: boolean
  unableToLeave?: boolean
  locationContext?: string
}

export interface ClarificationOption {
  id: string
  /** UI label key (labels live in ui.ts so localization stays in one place). */
  labelKey: UIKey
  /** Picking this resolves to a verified situation (or the honest fallback). */
  situationId?: RouteSituationId
  /** Picking this advances to another clarification step. */
  nextStepId?: string
  /** Picking this is itself a safety signal (e.g. "threatening or hurting me"). */
  safetySignal?: boolean
  /** Picking this routes to the Questioned-vs-Arrested decision tool. */
  uncertaintySignal?: boolean
  /** "I'm not sure" — the option exists so the user is never stuck. */
  unsure?: boolean
}

export interface ClarificationStep {
  id: string
  /** Asked in everyday language — the user never needs a legal term. */
  questionKey: UIKey
  /** "We ask this because…" — a subtle trust-building explanation. */
  whyKey: UIKey
  options: ClarificationOption[]
}

export interface Clarification {
  steps: ClarificationStep[]
  currentStepId: string
}

export interface SituationUnderstanding {
  situationId: RouteSituationId
  confidence: Confidence
  context: NavigatorContext
  needsClarification: boolean
  clarification?: Clarification
  /** Immediate danger detected — the UI must show the safety card first. */
  safetyConcern: boolean
  /** "Questioned or arrested?" — the UI routes to the decision tool. */
  arrestUncertainty: boolean
  matchedTerms: string[]
}

export interface SituationUnderstandingProvider {
  name: 'local' | 'hybrid'
  /** Honest disclosure shown in the UI (where the description is processed). */
  processingNoteKey: UIKey
  /** Whether an external AI service is configured for this build. */
  aiAssistAvailable: boolean
  /** Whether the user has opted in to AI assist (default: off). */
  aiAssistEnabled: boolean
  setAiAssistEnabled: (on: boolean) => void
  analyze: (userText: string) => Promise<SituationUnderstanding>
  resolveClarification: (stepId: string, optionId: string) => SituationUnderstanding
}

