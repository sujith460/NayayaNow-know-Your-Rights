/* ────────────────────────────────────────────────────────────────
   Local engine (fully on-device, deterministic, private)
──────────────────────────────────────────────────────────────── */

function hasAny(text: string, terms: readonly string[]): boolean {
  return terms.some((term) => text.includes(term))
}

/** True when the description carries a signal beyond a bare "stopped me". */
function hasContextBeyondStop(ctx: NavigatorContext): boolean {
  return Boolean(
    ctx.documentsRequested ||
      ctx.questioning ||
      ctx.searchInvolved ||
      ctx.propertyInvolved ||
      ctx.phoneInvolved ||
      ctx.moneyRequested ||
      ctx.harmMentioned ||
      ctx.arrestMentioned ||
      ctx.trafficMentioned ||
      ctx.challanMentioned
  )
}

function detectVehicleType(text: string): string | undefined {
  if (/(bike|scooter|motorcycle|two-wheeler|बाइक|स्कूटर|బైక్|స్కూటర్)/.test(text)) return 'two-wheeler'
  if (/(car|four-wheeler|गाड़ी|कार|కారు)/.test(text)) return 'car'
  if (/(vehicle|वाहन|వాహనం)/.test(text)) return 'other'
  return undefined
}

function buildContext(text: string): NavigatorContext {
  return {
    vehicleInvolved: hasAny(text, KW.vehicle),
    vehicleType: detectVehicleType(text),
    documentsRequested: hasAny(text, KW.documents),
    questioning: hasAny(text, KW.questioning) || hasAny(text, KW.station),
    searchInvolved: hasAny(text, KW.search),
    propertyInvolved: hasAny(text, KW.propertyTaken),
    phoneInvolved: hasAny(text, KW.phone),
    moneyRequested: hasAny(text, KW.money),
    arrestMentioned: hasAny(text, KW.arrestWords),
    harmMentioned: hasAny(text, KW.harmWords),
    trafficMentioned: hasAny(text, KW.vehicle) || hasAny(text, KW.challan),
    challanMentioned: hasAny(text, KW.challan),
    unableToLeave: hasAny(text, DETENTION_PHRASES)
  }
}

/** Local-classifier confidence is a number 0–1; HIGH needs a clear winner. */
const HIGH_CONFIDENCE = 0.72

/** A clarification-focused understanding for a given step (or the first step). */
export function getClarification(
  stepId: string,
  context: NavigatorContext = {},
  safetyConcern = false,
  arrestUncertainty = false,
  matchedTerms: string[] = []
): SituationUnderstanding {
  const currentStepId = STEPS[stepId] ? stepId : 'where'
  return {
    situationId: 'UNKNOWN',
    confidence: 'LOW',
    context,
    needsClarification: true,
    clarification: { steps: ALL_STEPS, currentStepId },
    safetyConcern,
    arrestUncertainty,
    matchedTerms
  }
}

export function analyzeLocal(text: string): SituationUnderstanding {
  const lower = text.toLowerCase().trim()
  const context = buildContext(lower)

  const safetyConcern = hasAny(lower, SAFETY_PHRASES)
  const arrestUncertainty = hasAny(lower, ARREST_DOUBT_PHRASES) || hasAny(lower, DETENTION_PHRASES)

  const classified = classify(text)
  const highConf = classified.situationId !== 'UNKNOWN' && classified.confidence >= HIGH_CONFIDENCE

  const base = (patch: Partial<SituationUnderstanding>): SituationUnderstanding => ({
    situationId: 'UNKNOWN',
    confidence: 'LOW',
    context,
    needsClarification: false,
    safetyConcern,
    arrestUncertainty,
    matchedTerms: classified.matchedTerms,
    ...patch
  })

  // 1. Immediate danger — safety card comes first, always.
  if (safetyConcern) {
    return base({ situationId: 'POLICE_ABUSE', confidence: 'HIGH' })
  }

  // 2. "I don't know if I am arrested" / "told to come with them" — we never
  //    decide an arrest for the user; the decision tool does.
  if (arrestUncertainty) {
    return base({ situationId: 'UNKNOWN', confidence: 'LOW' })
  }

  // 2b. A bare "police stopped me" is genuinely ambiguous (documents? search?
  //     money? arrest?) — start the guided everyday-language flow instead of
  //     guessing which guide fits. With any real signal we go straight to the
  //     verified guide.
  const bareStop =
    classified.situationId === 'POLICE_QUESTIONING' &&
    hasAny(lower, KW.stopWords) &&
    !hasContextBeyondStop(context)
  if (bareStop) {
    return getClarification('where', context, safetyConcern, arrestUncertainty, classified.matchedTerms)
  }

  // 3. High-confidence local classification → verified guide directly.
  if (highConf) {
    return base({ situationId: classified.situationId, confidence: 'HIGH' })
  }

  // 4. Any real classifier match (score ≥ 3) → verified guide, MEDIUM.
  if (classified.situationId !== 'UNKNOWN' && classified.confidence >= 0.6) {
    return base({ situationId: classified.situationId, confidence: 'MEDIUM' })
  }

  // 5. "I don't know what applies" → honest fallback, never a guess.
  if (hasAny(lower, UNSURE_PHRASES)) {
    return base({ situationId: 'UNKNOWN', confidence: 'LOW' })
  }

  // 6. Structured context routing (no classifier match). Traffic is handled
  //    honestly: challan/fine law is NOT in the verified KB yet, so we never
  //    invent Motor Vehicles Act guidance.
  if (context.challanMentioned) {
    return base({ situationId: 'TRAFFIC_UNVERIFIED', confidence: 'MEDIUM' })
  }
  if (context.searchInvolved) return base({ situationId: 'SEARCH', confidence: 'MEDIUM' })
  if ((context.vehicleInvolved || context.phoneInvolved || context.documentsRequested) && context.propertyInvolved) {
    return base({ situationId: 'PROPERTY_SEIZED', confidence: 'MEDIUM' })
  }
  if (context.propertyInvolved) return base({ situationId: 'PROPERTY_SEIZED', confidence: 'MEDIUM' })
  if (context.questioning || context.documentsRequested) {
    return base({ situationId: 'POLICE_QUESTIONING', confidence: 'MEDIUM' })
  }
  if (context.trafficMentioned && (context.vehicleInvolved || hasAny(lower, KW.stopWords))) {
    return base({ situationId: 'POLICE_QUESTIONING', confidence: 'MEDIUM' })
  }
  if (context.moneyRequested) return base({ situationId: 'BRIBE', confidence: 'MEDIUM' })
  if (context.harmMentioned) return base({ situationId: 'POLICE_ABUSE', confidence: 'MEDIUM' })
  if (context.arrestMentioned) return base({ situationId: 'ARREST', confidence: 'MEDIUM' })
  if (context.trafficMentioned) {
    return base({ situationId: 'TRAFFIC_UNVERIFIED', confidence: 'MEDIUM' })
  }

  // 7. Nothing matched → dynamic everyday-language clarification, then fall
  //    back safely. Never a guess about legal rights.
  return getClarification('where', context, safetyConcern, arrestUncertainty, classified.matchedTerms)
}

/** Resolve one clarification option (terminal situation, safety, or next step). */
export function resolveClarificationStep(stepId: string, optionId: string): SituationUnderstanding {
  const step = STEPS[stepId]
  const option = step?.options.find((o) => o.id === optionId)
  if (!option) {
    return {
      situationId: 'UNKNOWN',
      confidence: 'LOW',
      context: {},
      needsClarification: false,
      safetyConcern: false,
      arrestUncertainty: false,
      matchedTerms: []
    }
  }
  if (option.safetySignal) {
    return {
      situationId: 'POLICE_ABUSE',
      confidence: 'HIGH',
      context: {},
      needsClarification: false,
      safetyConcern: true,
      arrestUncertainty: false,
      matchedTerms: []
    }
  }
  if (option.uncertaintySignal) {
    return {
      situationId: 'UNKNOWN',
      confidence: 'LOW',
      context: {},
      needsClarification: false,
      safetyConcern: false,
      arrestUncertainty: true,
      matchedTerms: []
    }
  }
  if (option.situationId) {
    return {
      situationId: option.situationId,
      confidence: 'MEDIUM',
      context: {},
      needsClarification: false,
      safetyConcern: false,
      arrestUncertainty: false,
      matchedTerms: []
    }
  }
  if (option.nextStepId) {
    return getClarification(option.nextStepId)
  }
  return getClarification('where')
}

/* ────────────────────────────────────────────────────────────────
   LLM provider (optional) — situation understanding ONLY.
   Structured JSON is validated before use; anything invalid fails
   closed and the hybrid falls back to the local engine.
──────────────────────────────────────────────────────────────── */

const AI_ALLOWED_IDS = new Set<string>([
  'POLICE_QUESTIONING', 'ARREST', 'FIR_REFUSED', 'SEARCH', 'PROPERTY_SEIZED',
  'POLICE_ABUSE', 'BRIBE', 'COMPLAINT', 'WOMEN_AND_POLICE', 'PROLONGED_DETENTION',
  'POLICE_REFUSED_HELP', 'POLICE_NOTICE', 'POLICE_AT_HOME', 'NOT_SURE', 'UNKNOWN',
  'TRAFFIC_UNVERIFIED', 'ARREST_UNCERTAIN'
])

const CONTEXT_KEYS = [
  'vehicleInvolved', 'documentsRequested', 'questioning', 'searchInvolved',
  'propertyInvolved', 'phoneInvolved', 'moneyRequested', 'arrestMentioned',
  'harmMentioned', 'trafficMentioned', 'challanMentioned', 'unableToLeave'
] as const

/** The ONLY shape the LLM is allowed to produce (after validation). */
export interface AISituationResult {
  situationId: string
  confidence: Confidence
  context: NavigatorContext
  needsClarification: boolean
  clarifyingQuestion?: string
}

/**
 * Strict schema validation for the model's structured output. Only the listed
 * fields are ever read — any legal content the model might emit is ignored.
 * Returns null when the output is unusable (caller falls back safely).
 */
export function validateAIResult(raw: unknown): AISituationResult | null {
  if (typeof raw !== 'object' || raw === null) return null
  const r = raw as Record<string, unknown>
  if (typeof r.situationId !== 'string' || !AI_ALLOWED_IDS.has(r.situationId)) return null
  if (r.confidence !== 'HIGH' && r.confidence !== 'MEDIUM' && r.confidence !== 'LOW') return null

  const context: NavigatorContext = {}
  if (typeof r.context === 'object' && r.context !== null) {
    const c = r.context as Record<string, unknown>
    for (const key of CONTEXT_KEYS) {
      if (typeof c[key] === 'boolean') context[key] = c[key] as boolean
    }
    if (typeof c.vehicleType === 'string') context.vehicleType = c.vehicleType
    if (typeof c.locationContext === 'string') context.locationContext = c.locationContext
  }

  return {
    situationId: r.situationId,
    confidence: r.confidence,
    context,
    needsClarification: r.needsClarification === true,
    clarifyingQuestion: typeof r.clarifyingQuestion === 'string' ? r.clarifyingQuestion : undefined
  }
}

export function aiResultToUnderstanding(valid: AISituationResult): SituationUnderstanding {
  const base: SituationUnderstanding = {
    situationId: 'UNKNOWN',
    confidence: valid.confidence,
    context: valid.context,
    needsClarification: false,
    safetyConcern: false,
    arrestUncertainty: false,
    matchedTerms: []
  }

  // ARREST_UNCERTAIN is not a verified page — the Questioned-vs-Arrested
  // decision tool explains that the rules depend on the circumstances.
  if (valid.situationId === 'ARREST_UNCERTAIN') {
    return { ...base, arrestUncertainty: true }
  }
  if (valid.needsClarification) {
    // We never render the model's own question text. Clarification goes
    // through the curated everyday-language flow (max 3 questions).
    return getClarification('where', valid.context)
  }
  if (valid.situationId === 'UNKNOWN' || valid.situationId === 'NOT_SURE') {
    return base
  }
  return { ...base, situationId: valid.situationId as RouteSituationId }
}

const AI_TIMEOUT_MS = 12_000

async function llmAnalyze(text: string): Promise<SituationUnderstanding | null> {
  const cfg = getAIConfig()
  if (!cfg.available || !cfg.endpoint) return null

  try {
    const controller = new AbortController()
    const timer = setTimeout(() => controller.abort(), AI_TIMEOUT_MS)
    let res: Response
    try {
      res = await fetch(cfg.endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
        body: JSON.stringify({ text }),
        signal: controller.signal
      })
    } finally {
      clearTimeout(timer)
    }
    if (!res.ok) return null
    const data: unknown = await res.json().catch(() => null)
    const valid = validateAIResult(data)
    return valid ? aiResultToUnderstanding(valid) : null
  } catch {
    return null
  }
}

/* ────────────────────────────────────────────────────────────────
   Providers — local (always) and hybrid (local first, optional AI).
──────────────────────────────────────────────────────────────── */

export type LLMAnalyzer = (text: string) => Promise<SituationUnderstanding | null>

export function createHybridProvider(opts?: { llm?: LLMAnalyzer; available?: boolean }): SituationUnderstandingProvider {
  const llm = opts?.llm ?? llmAnalyze
  const available = opts?.available ?? getAIConfig().available
  let enabled = false

  return {
    name: 'hybrid',
    get processingNoteKey(): UIKey {
      if (!available) return 'anOnDevice'
      return enabled ? 'anAIAssistNote' : 'anPrivateModeNote'
    },
    get aiAssistAvailable() {
      return available
    },
    get aiAssistEnabled() {
      return enabled
    },
    setAiAssistEnabled(on: boolean) {
      enabled = on
    },
    async analyze(text: string): Promise<SituationUnderstanding> {
      const local = analyzeLocal(text)

      // Safety and arrest-uncertainty are never delegated to AI, and a
      // confident local match needs no network call (speed + privacy).
      if (local.safetyConcern || local.arrestUncertainty || local.confidence === 'HIGH') return local

      // MEDIUM / LOW / UNKNOWN → optional AI situation understanding.
      if (enabled && available) {
        const ai = await llm(text)
        if (ai) return ai
        // AI unavailable, rate-limited, invalid JSON or timeout → the local
        // result is used (verified guide, curated clarification, or honest
        // UNKNOWN). The app never breaks because of AI.
      }
      return local
    },
    resolveClarification: resolveClarificationStep
  }
}

/** The active provider — local first, AI assist only when configured + opted in. */
export const hybridSituationProvider = createHybridProvider()

/** Pure local provider (used by tests and as the honest baseline). */
export const localSituationProvider: SituationUnderstandingProvider = {
  name: 'local',
  processingNoteKey: 'anOnDevice',
  aiAssistAvailable: false,
  aiAssistEnabled: false,
  setAiAssistEnabled() {
    /* local provider has no external assist */
  },
  async analyze(text: string): Promise<SituationUnderstanding> {
    return analyzeLocal(text)
  },
  resolveClarification: resolveClarificationStep
}

export function getSituationProvider(): SituationUnderstandingProvider {
  return hybridSituationProvider
}
